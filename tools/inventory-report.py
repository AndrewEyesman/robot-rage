#!/usr/bin/env python3
"""Merge the inventory slices into docs/inventory.json and render docs/inventory.md.

  tools/inventory-report.py [<slice.json>...] --overrides tools/inventory-overrides.json

Without slices, docs/inventory.json itself is the base (the usual case: record a fix
in the overrides file and re-run).

Each slice is a list of {name, category, uses, movies, verdict, impact, needs_adobe,
game_usage, dirplayer, evidence}. Overrides change verdict/evidence for items fixed or
checked since (keyed "category:name", lowercase name).
"""
import argparse
import json
import os
from collections import Counter

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
IMPACT_ORDER = {"high": 0, "medium": 1, "low": 2}


def key(r):
    return f"{r['category']}:{r['name'].lower()}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("slices", nargs="*")
    ap.add_argument("--overrides")
    a = ap.parse_args()
    rows = []
    for path in a.slices or [os.path.join(ROOT, "docs", "inventory.json")]:
        rows += json.load(open(path))
    overrides = json.load(open(a.overrides)) if a.overrides else {}
    seen = set()
    merged = []
    for r in rows:
        k = key(r)
        if k in seen and r.get("verdict") == "game":
            continue
        seen.add(k)
        r = dict(r)
        if k in overrides:
            r.update(overrides[k])
        merged.append(r)
    for k, o in overrides.items():
        if k not in seen:
            cat, name = k.split(":", 1)
            merged.append({"category": cat, "name": name, **o})
    merged.sort(key=lambda r: (r["category"], r["name"].lower()))
    json.dump(merged, open(os.path.join(ROOT, "docs", "inventory.json"), "w"), indent=1)

    director = [r for r in merged if r.get("verdict") != "game"]
    by = Counter(r["verdict"] for r in director)
    grid = Counter((r["verdict"], r.get("impact", "low")) for r in director)
    adobe = sum(1 for r in director if r.get("needs_adobe") and r["verdict"] in ("wrong", "unclear"))
    cats = Counter(r["category"].split(":")[0] for r in director)

    out = []
    w = out.append
    w("# Director feature inventory\n")
    w("Every Director feature the game's Lingo uses, checked against dirplayer. Generated by")
    w("`tools/inventory-report.py` from `docs/inventory.json`. Don't edit by hand: change an")
    w("entry in the JSON (or `tools/inventory-overrides.json`) and re-run.\n")
    w("Names come from `tools/lingo-inventory.py` over the decompiled scripts (all movies,")
    w("including the fan wrappers). Each was classified by reading how the game uses it and")
    w("how dirplayer implements that use, against Director's documentation and ScummVM's")
    w("Director engine for 2D. `works` therefore means \"matches the documentation as far as")
    w("code reading can tell\", not \"proven against Adobe's player\". Items marked")
    w("**needs Adobe** are to be settled with Ghidra. `fixed` means fixed and tested since.\n")
    w("## Counts\n")
    w(f"{len(director)} Director features ({', '.join(f'{v} {k}' for k, v in sorted(cats.items()))}).\n")
    w("| verdict | high | medium | low | total |")
    w("| --- | ---: | ---: | ---: | ---: |")
    for v in ("wrong", "unclear", "fixed", "works"):
        w(f"| {v} | {grid[(v, 'high')]} | {grid[(v, 'medium')]} | {grid[(v, 'low')]} | {by[v]} |")
    w(f"\nImpact is impact on play: high blocks or visibly breaks single-player (driving,")
    w("collisions, weapons, garage, robot list, workshop tabs), medium is visible but not")
    w(f"blocking, low is cosmetic, rare or outside single-player. {adobe} open items need")
    w("Adobe's code to settle.\n")

    def table(verdict, title):
        items = sorted((r for r in director if r["verdict"] == verdict),
                       key=lambda r: (IMPACT_ORDER.get(r.get("impact", "low"), 3), r["name"].lower()))
        w(f"## {title} ({len(items)})\n")
        w("| impact | feature | kind | what's wrong / open | where |")
        w("| --- | --- | --- | --- | --- |")
        for r in items:
            ev = (r.get("evidence") or "").replace("|", "\\|").replace("\n", " ")
            if len(ev) > 420:
                ev = ev[:417] + "..."
            flag = " **needs Adobe**" if r.get("needs_adobe") else ""
            where = (r.get("dirplayer") or "").replace("|", "\\|")
            if len(where) > 90:
                where = where[:87] + "..."
            w(f"| {r.get('impact', '')} | `{r['name']}` | {r['category']} | {ev}{flag} | {where} |")
        w("")

    table("wrong", "Wrong")
    table("unclear", "Unclear")
    table("fixed", "Fixed")
    w("## Works\n")
    works = sorted((r for r in director if r["verdict"] == "works"), key=lambda r: (r["category"], r["name"].lower()))
    for cat in sorted({r["category"] for r in works}):
        w(f"- **{cat}**: " + ", ".join(f"`{r['name']}`" for r in works if r["category"] == cat))
    w("")
    open(os.path.join(ROOT, "docs", "inventory.md"), "w").write("\n".join(out))
    print(dict(by), "needs adobe:", adobe)


if __name__ == "__main__":
    main()
